"""
Generate the ArUco marker textures and Gazebo models used as docking targets.

Each marker is a DICT_4X4_50 code (0.15 m) on a white square plate (0.20 m), so the
code is 75% of the image side and a 0.025 m quiet zone surrounds it. The output is
committed, so building the workspace does not depend on running this script.
"""

import argparse
import os

import cv2
import numpy as np

MARKER_IDS = range(5)
CODE_PIXELS = 600
PAD_PIXELS = 100  # 600 / 0.15 m = 4000 px/m, so 100 px is the 0.025 m quiet zone
PLATE_SIZE = 0.20
PLATE_DEPTH = 0.05

MODEL_CONFIG = """<?xml version="1.0"?>
<model>
  <name>aruco_marker_{id}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <author><name>Pavan Patil</name></author>
  <description>ArUco DICT_4X4_50 marker {id} on a white plate; +x is the face.</description>
</model>
"""

# The plate is a box behind the face plane; the printed texture sits on a plane facing +x,
# so the model's +x axis is the docking normal and the origin is the centre of the face.
MODEL_SDF = """<?xml version="1.0"?>
<!-- Copyright 2026 Pavan Patil, SPDX-License-Identifier: Apache-2.0
     Generated by scripts/generate_markers.py; do not edit by hand. -->
<sdf version="1.9">
  <model name="aruco_marker_{id}">
    <static>true</static>
    <link name="link">
      <visual name="plate">
        <pose>{plate_x} 0 0 0 0 0</pose>
        <geometry><box><size>{depth} {size} {size}</size></box></geometry>
        <material>
          <ambient>1 1 1 1</ambient>
          <diffuse>1 1 1 1</diffuse>
          <specular>0 0 0 1</specular>
        </material>
      </visual>
      <collision name="plate_collision">
        <pose>{plate_x} 0 0 0 0 0</pose>
        <geometry><box><size>{depth} {size} {size}</size></box></geometry>
      </collision>
      <visual name="face">
        <pose>0.0005 0 0 0 0 0</pose>
        <geometry>
          <plane><normal>1 0 0</normal><size>{size} {size}</size></plane>
        </geometry>
        <material>
          <ambient>1 1 1 1</ambient>
          <diffuse>1 1 1 1</diffuse>
          <specular>0 0 0 1</specular>
          <pbr>
            <metal>
              <albedo_map>
                model://aruco_marker_{id}/materials/textures/marker_{id}.png
              </albedo_map>
              <roughness>1.0</roughness>
              <metalness>0.0</metalness>
            </metal>
          </pbr>
        </material>
      </visual>
    </link>
  </model>
</sdf>
"""


def draw_marker(dictionary, marker_id):
    """
    Render one marker image on OpenCV 4.6 or newer.

    The detector and the simulated target must agree on the dictionary, so the texture
    is produced with the same OpenCV ArUco API the detector uses.
    """
    if hasattr(cv2.aruco, 'generateImageMarker'):
        return cv2.aruco.generateImageMarker(dictionary, marker_id, CODE_PIXELS)
    return cv2.aruco.drawMarker(dictionary, marker_id, CODE_PIXELS, borderBits=1)


def write_marker(models_dir, marker_id):
    """Write the texture PNG and model files for one marker ID into the models folder."""
    dictionary = cv2.aruco.getPredefinedDictionary(cv2.aruco.DICT_4X4_50)
    code = draw_marker(dictionary, marker_id)
    image = np.pad(code, PAD_PIXELS, constant_values=255)

    model_dir = os.path.join(models_dir, 'aruco_marker_%d' % marker_id)
    texture_dir = os.path.join(model_dir, 'materials', 'textures')
    os.makedirs(texture_dir, exist_ok=True)
    cv2.imwrite(os.path.join(texture_dir, 'marker_%d.png' % marker_id), image)
    with open(os.path.join(model_dir, 'model.config'), 'w') as f:
        f.write(MODEL_CONFIG.format(id=marker_id))
    with open(os.path.join(model_dir, 'model.sdf'), 'w') as f:
        f.write(MODEL_SDF.format(id=marker_id, size=PLATE_SIZE, depth=PLATE_DEPTH,
                                 plate_x=-PLATE_DEPTH / 2))


def main():
    """Generate every marker model, so the worlds have docking targets with known IDs."""
    default_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'models')
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--models-dir', default=default_dir)
    args = parser.parse_args()
    for marker_id in MARKER_IDS:
        write_marker(args.models_dir, marker_id)
        print('wrote marker', marker_id)


if __name__ == '__main__':
    main()
